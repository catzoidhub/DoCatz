// bun --tsconfig-override=tsconfig.node.json scripts/mcatzp-tools.ts — writes DoCatz's MCatzP tools as Markdown, from the
// registry itself, so the reference never drifts (MCatzP #23, Catzoid #85). Runs nothing: only names, tiers and inputs.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { allActions } from '../src/main/mcatzp/registry';

const OUT = resolve(import.meta.dir, '../../MCatzP/docs/tools/docatz.md');
const TIER = { read: 'Read: runs at once, inside what is shared', change: 'Change: asks in DoCatz first', destructive: 'Destructive: you type a name in DoCatz, every time' } as const;

type Schema = { properties?: Record<string, { description?: string; enum?: string[]; type?: string | string[] }>; required?: string[] };
const inputs = (s: Schema) => {
  const entries = Object.entries(s.properties ?? {});
  if (!entries.length) return 'None.';
  return entries.map(([k, v]) => `\`${k}\`${s.required?.includes(k) ? '' : ' (optional)'}${v.enum ? `: one of ${v.enum.join(', ')}` : v.description ? `: ${v.description}` : ''}`).join('<br>');
};
const cell = (t: string) => t.replace(/\|/g, '\\|').replace(/\n/g, ' ');

const all = allActions();
let md = `# DoCatz tools\n\nGenerated by DoCatz's \`scripts/mcatzp-tools.ts\`: do not edit by hand. A client sees each one as \`docatz_<name>\`, and only those that Settings → MCatzP allows. Every tool runs on macOS and Windows, unless it says Windows.\n`;
for (const tier of ['read', 'change', 'destructive'] as const) {
  const list = all.filter((a) => a.tier === tier);
  md += `\n## ${TIER[tier]} (${list.length})\n\n| Tool | What it does | Inputs |\n|---|---|---|\n`;
  for (const a of list) md += `| \`${a.name}\` | ${cell(a.description)} | ${cell(inputs(a.input as Schema))} |\n`;
}
writeFileSync(OUT, md);
console.log(`${all.length} tools → ${OUT}`);
